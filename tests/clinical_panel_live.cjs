const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const { startIsolatedBrowser } = require('./helpers/isolated_browser.cjs');
const { ensureSyntheticFixtures } = require('./helpers/synthetic_fixtures.cjs');
(async () => {
  const server = await startIsolatedBrowser();
  try {
    const page = await server.browser.newPage({viewport:{width:1440,height:1000}});
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(server.base+'/#login');
    await page.locator('[name=username]').fill('doctor');
    await page.locator('[name=password]').fill(server.password);
    await page.locator('#authForm button[type=submit]').click();
    await page.waitForFunction(() => location.hash === '#dashboard');
    const token = await page.evaluate(async () => (await import('/static/app/state.js')).state.token);
    const headers = {Authorization:'Bearer '+token, 'Idempotency-Key':crypto.randomUUID()};
    const created = await page.request.post(server.base+'/api/cases',{headers,data:{patient_id:'123456789',study_date:'2026-11-02',active_ovary_side:'LEFT',contralateral_status:'NOT_VISUALIZED'}});
    assert.equal(created.status(),200,await created.text());
    const id = (await created.json()).study_id;
    const tab_id=crypto.randomUUID(), page_instance_id=crypto.randomUUID();
    const leaseResponse = await page.request.post(server.base+`/api/workspace/cases/${id}/lease`,{headers,data:{tab_id,page_instance_id}});
    const lease = await leaseResponse.json(); assert.equal(lease.granted,true);
    const writeHeaders = {...headers,'Idempotency-Key':crypto.randomUUID(),'X-Case-Lease-Token':lease.lease_token,'X-Case-Page-Instance-Id':page_instance_id};
    const uploaded = await page.request.post(server.base+'/api/upload',{headers:writeHeaders,multipart:{study_id:id,laterality:'L',file:{name:'synthetic.png',mimeType:'image/png',buffer:fs.readFileSync(ensureSyntheticFixtures().left)}}});
    assert.equal(uploaded.status(),200,await uploaded.text());
    const imageId = (await uploaded.json()).image_id;
    const prediction=await page.request.post(server.base+'/api/predict/'+imageId,{headers:writeHeaders});
    assert.equal(prediction.status(),200,await prediction.text());
    await page.request.delete(server.base+`/api/workspace/cases/${id}/lease`,{headers,data:{lease_token:lease.lease_token,page_instance_id}});
    await page.goto(server.base+'/#viewer/'+id);
    await page.locator('#oradsScore').waitFor();
    await page.waitForFunction(() => !document.querySelector('#oradsScore').disabled);
    assert.equal(await page.locator('#oradsQuickPickMenu').count(),0);
    assert.equal(await page.locator('#assessmentAdvanced').getAttribute('open'),null);
    fs.mkdirSync('artifacts/clinical_panel_compact',{recursive:true});
    await page.screenshot({path:'artifacts/clinical_panel_compact/live-panel-desktop.png'});
    await page.setViewportSize({width:390,height:1000});
    await page.locator('[data-action="panel-toggle"]').click();
    await page.locator('#clinicalPanel').evaluate(element=>{element.scrollTop=0;});
    await page.screenshot({path:'artifacts/clinical_panel_compact/live-panel-mobile.png'});
    const mic = await page.locator('#dictationRecord').boundingBox();
    assert.ok(mic && mic.width >= 44 && mic.width <= 48, 'Microphone is compact and usable');
    await page.locator('[data-action="panel-toggle"]').click();
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#iotaMorphology').selectOption('Nang đơn thùy dịch trong');
    await page.locator('#morphology').fill('Mô tả hình thái riêng');
    await page.locator('#notes').fill('Nhận định độc lập của bác sĩ');
    await page.locator('#oradsScore').selectOption('O-RADS 2');
    assert.equal(await page.locator('#assessmentSaveStatus').textContent(),'Chưa lưu');
    const saved = page.waitForResponse(r=>r.request().method()==='POST' && r.url().includes('/api/reviews/batch'));
    await page.locator('[data-action=save-review]').click();
    const ack=await saved; assert.equal(ack.status(),200,await ack.text());
    await page.goto(server.base+'/#viewer/'+id);
    await page.waitForFunction(() => document.querySelector('#notes')?.value === 'Nhận định độc lập của bác sĩ');
    assert.equal(await page.locator('#morphology').inputValue(),'Mô tả hình thái riêng');
    assert.equal(await page.locator('#oradsScore').inputValue(),'O-RADS 2');
    assert.equal(await page.locator('#assessmentSaveStatus').textContent(),'Đã lưu');
    await page.route('**/api/reviews/batch', route => route.abort('connectionreset'));
    await page.locator('#notes').fill('Thay đổi chưa được lưu');
    await page.locator('[data-action=save-review]').click();
    await page.waitForFunction(() => document.querySelector('#assessmentSaveStatus')?.textContent === 'Lưu không thành công');
    const unchanged=await page.request.get(server.base+'/api/cases/'+id,{headers});
    assert.equal((await unchanged.json()).images[0].review.clinical_notes,'Nhận định độc lập của bác sĩ');
    assert.equal(await page.locator('#notes').inputValue(),'Thay đổi chưa được lưu');
    assert.deepEqual(errors,[]);
    console.log('PASS: live save/reopen preserves notes/morphology/O-RADS; failed save retains draft and does not claim success');
  } finally { await server.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
