import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../frontend/app/image-classification.js', import.meta.url),'utf8');
const { classificationText, classificationNote } = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.match(classificationText(null), /chưa có kết quả/);
assert.match(classificationText({status:'UNAVAILABLE'}), /không khả dụng/);
const text = classificationText({status:'ABSTAIN',probabilities:{simple_cyst:.4,normal_ovary:.35,teratoma:.25}});
assert.match(text, /Chưa đủ tin cậy/);
assert.match(text, /40.0%/);
assert.match(text, /không phải xác suất mắc bệnh/);
assert.match(classificationText({status:'PREDICTED',suggested_label:'simple_cyst',probabilities:{simple_cyst:.8}}),/Nhãn ảnh được đề xuất: Nang đơn giản/);
console.log('PASS: image classification labels, abstention, unavailable and RUO copy');
const predicted = {status:'PREDICTED', suggested_label:'simple_cyst'};
const note = classificationNote(predicted, 'Mô tả do bác sĩ nhập');
assert.ok(note.startsWith('Mô tả do bác sĩ nhập\n'));
assert.match(note, /AI \(RUO, chưa xác nhận\)/);
assert.equal(classificationNote(predicted, note), note);
assert.equal(classificationNote({ ...predicted, status:'ABSTAIN' }), null);
assert.equal(classificationNote({ ...predicted, suggested_label:'invented' }), null);
